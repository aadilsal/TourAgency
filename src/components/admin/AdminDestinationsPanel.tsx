"use client";

import { useMutation, useQuery } from "convex/react";
import { api } from "@convex/_generated/api";
import { useConvexSessionToken } from "@/hooks/useConvexSessionToken";
import type { Id } from "@convex/_generated/dataModel";
import { useMemo, useRef, useState } from "react";
import { Pencil, Plus } from "lucide-react";
import { Modal } from "@/components/ui/Modal";
import { Button } from "@/components/ui/Button";
import { IconAction } from "@/components/admin/shared/IconAction";
import { toUserFacingErrorMessage } from "@/lib/userFriendlyError";
import { confirmDiscard } from "@/hooks/useUnsavedChangesGuard";
import { BulkUploadModal } from "@/components/admin/BulkUploadModal";
import { asNumber, asString, asStringArray } from "@/lib/bulkUpload/coerce";
import { importInBatches } from "@/lib/bulkUpload/importInBatches";
import {
  AdminField,
  InfoTip,
  RequiredFieldsNote,
  useRequiredFields,
} from "@/components/admin/shared/AdminField";
import { AdvancedSection, MoreMenu } from "@/components/admin/tour-form/fields";

type DestinationRow = {
  _id: Id<"destinations">;
  slug: string;
  name: string;
  line: string;
  description: string;
  heroStorageId?: Id<"_storage">;
  heroExternalUrl?: string;
  heroUrl?: string;
  matchTerms: string[];
  bestTime: string;
  tips: string[];
  costEstimate: string;
  bullets: string[];
  sortOrder: number;
  autoGenerated: boolean;
  tourCount: number;
};

function toLines(v: string[]): string {
  return v.join("\n");
}

/** The editable text of the destination modal, used to detect unsaved edits. */
type DestinationFormText = {
  name: string;
  slug: string;
  line: string;
  description: string;
  sortOrder: number;
  matchTermsInput: string;
  bestTime: string;
  tipsInput: string;
  costEstimate: string;
  bulletsInput: string;
};

const EMPTY_DESTINATION_FORM: DestinationFormText = {
  name: "",
  slug: "",
  line: "",
  description: "",
  sortOrder: 100,
  matchTermsInput: "",
  bestTime: "",
  tipsInput: "",
  costEstimate: "",
  bulletsInput: "",
};

function fromLines(v: string): string[] {
  return v
    .split("\n")
    .map((s) => s.trim())
    .filter(Boolean);
}

export function AdminDestinationsPanel() {
  const sessionToken = useConvexSessionToken();
  const canMutate = typeof sessionToken === "string";
  const rows = useQuery(
    api.destinations.listForAdmin,
    canMutate ? { sessionToken } : "skip",
  );
  const seedDestinations = useMutation(api.destinations.seedDefaults);
  const createDestination = useMutation(api.destinations.createDestination);
  const updateDestination = useMutation(api.destinations.updateDestination);
  const deleteDestination = useMutation(api.destinations.deleteDestination);
  const bulkUpsert = useMutation(api.destinations.bulkUpsert);
  const generateHeroUploadUrl = useMutation(api.destinations.generateDestinationHeroUploadUrl);

  const [modalOpen, setModalOpen] = useState(false);
  const [editingId, setEditingId] = useState<Id<"destinations"> | null>(null);

  const [name, setName] = useState("");
  const [slug, setSlug] = useState("");
  const [line, setLine] = useState("");
  const [description, setDescription] = useState("");
  // `undefined` = leave hero unchanged; `null` = remove it; an id = a newly uploaded image.
  const [heroStorageId, setHeroStorageId] = useState<Id<"_storage"> | null | undefined>(undefined);
  const [heroPreviewUrl, setHeroPreviewUrl] = useState<string | null>(null);
  const [heroUploading, setHeroUploading] = useState(false);
  const [sortOrder, setSortOrder] = useState(100);
  const [matchTermsInput, setMatchTermsInput] = useState("");
  const [bestTime, setBestTime] = useState("");
  const [tipsInput, setTipsInput] = useState("");
  const [costEstimate, setCostEstimate] = useState("");
  const [bulletsInput, setBulletsInput] = useState("");

  const [msg, setMsg] = useState<string | null>(null);
  const [saving, setSaving] = useState(false);
  const [bulkOpen, setBulkOpen] = useState(false);
  // createDestination: name, line, description, bestTime, costEstimate are
  // non-optional v.string() args (the matching inputs were already `required`).
  const req = useRequiredFields(
    [
      { name: "name", label: "Name", value: name },
      { name: "line", label: "Short tagline", value: line },
      { name: "description", label: "Description", value: description },
      { name: "bestTime", label: "Best time", value: bestTime },
      { name: "costEstimate", label: "Cost estimate", value: costEstimate },
    ],
    { idPrefix: "destination-editor" },
  );

  const list = useMemo(() => (rows ?? []) as DestinationRow[], [rows]);

  /** Form text as it was when the modal opened. */
  const openedRef = useRef<DestinationFormText>(EMPTY_DESTINATION_FORM);
  const currentForm: DestinationFormText = {
    name,
    slug,
    line,
    description,
    sortOrder,
    matchTermsInput,
    bestTime,
    tipsInput,
    costEstimate,
    bulletsInput,
  };
  const dirty =
    modalOpen &&
    (heroStorageId !== undefined ||
      JSON.stringify(currentForm) !== JSON.stringify(openedRef.current));

  function applyForm(f: DestinationFormText) {
    openedRef.current = f;
    setName(f.name);
    setSlug(f.slug);
    setLine(f.line);
    setDescription(f.description);
    setSortOrder(f.sortOrder);
    setMatchTermsInput(f.matchTermsInput);
    setBestTime(f.bestTime);
    setTipsInput(f.tipsInput);
    setCostEstimate(f.costEstimate);
    setBulletsInput(f.bulletsInput);
  }

  function resetForm() {
    applyForm(EMPTY_DESTINATION_FORM);
    setHeroStorageId(undefined);
    setHeroPreviewUrl(null);
  }

  function openNew() {
    setEditingId(null);
    resetForm();
    req.reset();
    setMsg(null);
    setModalOpen(true);
  }

  function openEdit(d: DestinationRow) {
    setEditingId(d._id);
    applyForm({
      name: d.name,
      slug: d.slug,
      line: d.line,
      description: d.description,
      sortOrder: d.sortOrder,
      matchTermsInput: toLines(d.matchTerms),
      bestTime: d.bestTime,
      tipsInput: toLines(d.tips),
      costEstimate: d.costEstimate,
      bulletsInput: toLines(d.bullets),
    });
    setHeroStorageId(undefined);
    setHeroPreviewUrl(d.heroStorageId || d.heroExternalUrl ? d.heroUrl ?? null : null);
    req.reset();
    setMsg(null);
    setModalOpen(true);
  }

  async function onPickHero(e: React.ChangeEvent<HTMLInputElement>) {
    const input = e.target;
    const file = input.files?.[0];
    input.value = "";
    if (!file) return;
    if (!file.type.startsWith("image/")) {
      setMsg("Please choose an image file.");
      return;
    }
    const blobUrl = URL.createObjectURL(file);
    setHeroPreviewUrl(blobUrl);
    setHeroUploading(true);
    setMsg(null);
    try {
      if (!canMutate) throw new Error("Not authenticated");
      const postUrl = await generateHeroUploadUrl({ sessionToken });
      const res = await fetch(postUrl, {
        method: "POST",
        headers: { "Content-Type": file.type || "image/jpeg" },
        body: file,
      });
      if (!res.ok) throw new Error(`Upload failed (${res.status})`);
      const data = (await res.json()) as { storageId?: Id<"_storage"> };
      if (!data.storageId) throw new Error("No storageId returned");
      setHeroStorageId(data.storageId);
    } catch (err) {
      URL.revokeObjectURL(blobUrl);
      setHeroPreviewUrl(null);
      setMsg(toUserFacingErrorMessage(err));
    } finally {
      setHeroUploading(false);
    }
  }

  function onRemoveHero() {
    setHeroStorageId(null);
    setHeroPreviewUrl(null);
  }

  async function onSubmit(e: React.FormEvent) {
    e.preventDefault();
    if (!req.guardSubmit(e)) return;
    if (heroUploading) {
      setMsg("Wait for the image upload to finish before saving.");
      return;
    }
    setSaving(true);
    setMsg(null);

    const base = {
      name,
      slug: slug.trim() || undefined,
      line,
      description,
      sortOrder,
      matchTerms: fromLines(matchTermsInput),
      bestTime,
      tips: fromLines(tipsInput),
      costEstimate,
      bullets: fromLines(bulletsInput),
    };

    try {
      if (!canMutate) throw new Error("Not authenticated");
      if (editingId) {
        // Send only what changed in this modal, so a save can't roll back edits
        // made elsewhere (another admin, bulk import) since it was opened.
        const opened = openedRef.current;
        const changed = <K extends keyof DestinationFormText>(k: K) =>
          currentForm[k] !== opened[k];
        await updateDestination({
          sessionToken,
          destinationId: editingId,
          name: changed("name") ? base.name : undefined,
          slug: changed("slug") ? base.slug : undefined,
          line: changed("line") ? base.line : undefined,
          description: changed("description") ? base.description : undefined,
          sortOrder: changed("sortOrder") ? base.sortOrder : undefined,
          matchTerms: changed("matchTermsInput") ? base.matchTerms : undefined,
          bestTime: changed("bestTime") ? base.bestTime : undefined,
          tips: changed("tipsInput") ? base.tips : undefined,
          costEstimate: changed("costEstimate") ? base.costEstimate : undefined,
          bullets: changed("bulletsInput") ? base.bullets : undefined,
          heroStorageId,
        });
        setMsg("Destination updated.");
      } else {
        await createDestination({
          sessionToken,
          ...base,
          heroStorageId: heroStorageId ?? undefined,
        });
        setMsg("Destination created.");
      }
      setModalOpen(false);
    } catch (err) {
      setMsg(toUserFacingErrorMessage(err));
    } finally {
      setSaving(false);
    }
  }

  if (rows === undefined) {
    return <p className="text-sm text-brand-muted">Loading…</p>;
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center gap-2">
        <Button type="button" variant="primary" onClick={openNew}>
          <Plus className="h-4 w-4" aria-hidden />
          Add destination
        </Button>
        <MoreMenu
          items={[
            {
              label: "Upload many destinations from a spreadsheet",
              onSelect: () => setBulkOpen(true),
            },
            process.env.NODE_ENV === "development" && {
              label: "Seed sample destinations (developer only)",
              onSelect: () => {
                if (!canMutate) {
                  setMsg("You have been signed out. Refresh the page and sign in again.");
                  return;
                }
                void seedDestinations({ sessionToken }).catch((e) =>
                  setMsg(toUserFacingErrorMessage(e)),
                );
              },
            },
          ]}
        />
        {msg && !modalOpen ? (
          <span className="text-sm text-brand-muted">{msg}</span>
        ) : null}
      </div>

      <div className="overflow-x-auto rounded-xl border border-slate-200/90 bg-white shadow-sm">
        <table className="min-w-[760px] w-full text-left text-sm">
          <thead className="whitespace-nowrap border-b border-slate-200 bg-slate-50/90 text-xs font-semibold uppercase tracking-wide text-slate-500">
            <tr>
              <th className="px-4 py-3">Name</th>
              <th className="px-4 py-3">Position</th>
              <th className="px-4 py-3">Tours</th>
              <th className="px-4 py-3">Added</th>
              <th className="px-4 py-3 text-right">Actions</th>
            </tr>
          </thead>
          <tbody>
            {list.map((d) => (
              <tr key={d._id} className="border-b border-slate-100 last:border-0">
                <td className="px-4 py-3">
                  <span className="block font-medium text-brand-ink">{d.name}</span>
                  <span className="block text-xs text-slate-400">
                    <span className="sr-only">Web address: </span>/{d.slug}
                  </span>
                </td>
                <td className="px-4 py-3 text-slate-600">{d.sortOrder}</td>
                <td className="px-4 py-3 text-slate-600">{d.tourCount}</td>
                <td className="px-4 py-3">
                  <span
                    className={d.autoGenerated
                      ? "rounded-full bg-amber-100 px-2 py-0.5 text-xs font-bold text-amber-900"
                      : "rounded-full bg-emerald-100 px-2 py-0.5 text-xs font-bold text-emerald-900"}
                  >
                    {d.autoGenerated ? "Automatically" : "By you"}
                  </span>
                </td>
                <td className="px-4 py-3 text-right">
                  <div className="flex flex-wrap justify-end gap-1">
                    <IconAction
                      label="Edit destination"
                      icon={Pencil}
                      tone="neutral"
                      onClick={() => openEdit(d)}
                    />
                    <IconAction
                      label="Delete destination"
                      onClick={() => {
                        if (confirm("Delete this destination? Tours assigned to it will be unassigned.")) {
                          if (!canMutate) {
                            setMsg("You have been signed out. Refresh the page and sign in again.");
                            return;
                          }
                          void deleteDestination({
                            sessionToken,
                            destinationId: d._id,
                          }).catch((e) => setMsg(toUserFacingErrorMessage(e)));
                        }
                      }}
                    />
                  </div>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
        {list.length === 0 ? (
          <p className="p-6 text-sm text-slate-500">No destinations yet.</p>
        ) : null}
      </div>

      <Modal
        open={modalOpen}
        onClose={() => setModalOpen(false)}
        confirmClose={dirty}
        title={editingId ? "Edit destination" : "Add destination"}
        description="The details shown on this destination’s page on your website."
        panelClassName="max-w-2xl"
        fullscreenOnMobile
      >
        <form noValidate onSubmit={onSubmit} className="space-y-3">
          <RequiredFieldsNote />
          {msg && modalOpen ? (
            <p className="rounded-lg bg-amber-50 px-3 py-2 text-sm text-amber-900">
              {msg}
            </p>
          ) : null}

          <div className="grid gap-3 sm:grid-cols-2">
            <AdminField
              label="Name"
              htmlFor={req.id("name")}
              required
              tip="The destination name shown on its page, cards and the destinations list."
              error={req.errorFor("name")}
            >
              <input
                {...req.fieldProps("name")}
                className="mt-1 w-full rounded-lg border border-slate-200 px-3 py-2 text-sm"
                placeholder="e.g. Hunza Valley"
                value={name}
                onChange={(e) => setName(e.target.value)}
              />
            </AdminField>
            <AdminField
              label="Short tagline"
              htmlFor={req.id("line")}
              required
              tip="A one-line tagline shown under the name on destination cards and the page header."
              error={req.errorFor("line")}
            >
              <input
                {...req.fieldProps("line")}
                className="mt-1 w-full rounded-lg border border-slate-200 px-3 py-2 text-sm"
                placeholder="e.g. Apricot orchards and Rakaposhi views"
                value={line}
                onChange={(e) => setLine(e.target.value)}
              />
            </AdminField>
          </div>

          <div className="text-xs font-semibold text-slate-600">
            <div className="relative flex items-center gap-1">
              <span>Banner photo (optional)</span>
              <InfoTip label="About Banner photo">
                The large banner photo at the top of the destination page. Use a wide landscape image.
              </InfoTip>
            </div>
            <div className="mt-2 flex flex-wrap items-center gap-3">
              <div className="relative h-16 w-24 shrink-0 overflow-hidden rounded-lg border border-slate-200 bg-slate-100">
                {heroPreviewUrl ? (
                  /* eslint-disable-next-line @next/next/no-img-element -- blob + Convex URLs */
                  <img src={heroPreviewUrl} alt="" className="h-full w-full object-cover" />
                ) : (
                  <div className="flex h-full items-center justify-center px-1 text-center text-[10px] font-medium text-slate-500">
                    No image
                  </div>
                )}
              </div>
              <label className="inline-flex cursor-pointer items-center rounded-lg border border-slate-300 bg-white px-3 py-2 text-xs font-semibold text-brand-primary hover:bg-slate-50">
                <input
                  type="file"
                  accept="image/*"
                  className="sr-only"
                  disabled={heroUploading}
                  onChange={(e) => void onPickHero(e)}
                />
                {heroUploading ? "Uploading…" : heroPreviewUrl ? "Replace image" : "Upload image"}
              </label>
              {heroPreviewUrl ? (
                <IconAction label="Remove banner photo" onClick={onRemoveHero} />
              ) : null}
            </div>
          </div>

          <AdminField
            label="Description"
            htmlFor={req.id("description")}
            required
            tip="The intro paragraph on the destination page."
            error={req.errorFor("description")}
          >
            <textarea
              {...req.fieldProps("description")}
              rows={3}
              className="mt-1 w-full rounded-lg border border-slate-200 px-3 py-2 text-sm"
              placeholder="e.g. Hunza is a high mountain valley in Gilgit-Baltistan, known for Baltit Fort, Attabad Lake and views of Rakaposhi."
              value={description}
              onChange={(e) => setDescription(e.target.value)}
            />
          </AdminField>

          <AdminField
            label="Best time"
            htmlFor={req.id("bestTime")}
            required
            tip="When to visit, shown in the destination's travel info."
            error={req.errorFor("bestTime")}
          >
            <textarea
              {...req.fieldProps("bestTime")}
              rows={2}
              className="mt-1 w-full rounded-lg border border-slate-200 px-3 py-2 text-sm"
              placeholder="e.g. April to October; blossoms in April, autumn colours in late October."
              value={bestTime}
              onChange={(e) => setBestTime(e.target.value)}
            />
          </AdminField>

          <AdminField
            label="Tips (one per line)"
            htmlFor="destination-editor-tips"
            tip="Practical travel tips listed on the destination page."
            hint="Each line becomes one tip."
          >
            <textarea
              id="destination-editor-tips"
              aria-describedby="destination-editor-tips-hint"
              rows={3}
              className="mt-1 w-full rounded-lg border border-slate-200 px-3 py-2 text-sm"
              placeholder={"e.g. Carry cash; ATMs are limited past Gilgit\nPack a warm layer even in summer"}
              value={tipsInput}
              onChange={(e) => setTipsInput(e.target.value)}
            />
          </AdminField>

          <AdminField
            label="Cost estimate"
            htmlFor={req.id("costEstimate")}
            required
            tip="A rough budget guide shown on the destination page."
            error={req.errorFor("costEstimate")}
          >
            <textarea
              {...req.fieldProps("costEstimate")}
              rows={2}
              className="mt-1 w-full rounded-lg border border-slate-200 px-3 py-2 text-sm"
              placeholder="e.g. From USD 450 (about PKR 125,000) per person for 5 days, including transport and hotels."
              value={costEstimate}
              onChange={(e) => setCostEstimate(e.target.value)}
            />
          </AdminField>

          <AdminField
            label="Bullets (one per line)"
            htmlFor="destination-editor-bullets"
            tip="Short highlights shown as a bullet list on the destination page."
            hint="Each line becomes one bullet."
          >
            <textarea
              id="destination-editor-bullets"
              aria-describedby="destination-editor-bullets-hint"
              rows={3}
              className="mt-1 w-full rounded-lg border border-slate-200 px-3 py-2 text-sm"
              placeholder={"e.g. Sunrise over Rakaposhi\nBoat ride on Attabad Lake\nBaltit and Altit forts"}
              value={bulletsInput}
              onChange={(e) => setBulletsInput(e.target.value)}
            />
          </AdminField>

          <AdvancedSection forceOpen={Boolean(msg && /slug|address/i.test(msg))}>
            <AdminField
              label="Web address (auto from name)"
              htmlFor="destination-editor-slug"
              tip="The end of this destination page's web address, e.g. /destinations/hunza-valley. Changing it later breaks old links."
              hint="Leave blank to build it from the name."
            >
              <input
                id="destination-editor-slug"
                aria-describedby="destination-editor-slug-hint"
                className="mt-1 w-full rounded-lg border border-slate-200 px-3 py-2 text-sm"
                placeholder="e.g. hunza-valley"
                value={slug}
                onChange={(e) => setSlug(e.target.value)}
              />
            </AdminField>
            <AdminField
              label="Position in list"
              htmlFor="destination-editor-sort-order"
              tip="Lower numbers appear first in destination lists, e.g. 10 comes before 20."
            >
              <input
                id="destination-editor-sort-order"
                type="number"
                className="mt-1 w-full rounded-lg border border-slate-200 px-3 py-2 text-sm"
                placeholder="e.g. 10"
                value={sortOrder}
                onChange={(e) => setSortOrder(Number(e.target.value) || 0)}
              />
            </AdminField>
            <AdminField
              label="Other spellings / nearby places (one per line)"
              htmlFor="destination-editor-match-terms"
              tip="A tour whose location contains any of these words is listed on this destination page automatically."
              hint="One per line, e.g. nearby towns and other ways of spelling the name."
            >
              <textarea
                id="destination-editor-match-terms"
                aria-describedby="destination-editor-match-terms-hint"
                rows={3}
                className="mt-1 w-full rounded-lg border border-slate-200 px-3 py-2 text-sm"
                placeholder={"e.g. hunza\nkarimabad\nattabad"}
                value={matchTermsInput}
                onChange={(e) => setMatchTermsInput(e.target.value)}
              />
            </AdminField>
          </AdvancedSection>

          <div className="flex flex-wrap gap-2 pt-2">
            <Button type="submit" {...req.submitProps} disabled={saving}>
              {saving ? "Saving…" : editingId ? "Save changes" : "Create destination"}
            </Button>
            <Button
              type="button"
              variant="secondary"
              onClick={() => {
                if (confirmDiscard(dirty)) setModalOpen(false);
              }}
            >
              Cancel
            </Button>
          </div>
        </form>
      </Modal>

      <BulkUploadModal
        open={bulkOpen}
        onClose={() => setBulkOpen(false)}
        title="Upload many destinations from a spreadsheet"
        description="Upload an Excel (.xlsx) or .json file with one destination per row. Rows with the same name (or web address) as an existing destination update it; new names are added."
        templateHint={
          <div className="space-y-1">
            <p className="font-semibold">Spreadsheet columns</p>
            <p className="font-mono text-xs">
              slug, name, line, description, heroExternalUrl, matchTerms, bestTime, tips, costEstimate, bullets, sortOrder
            </p>
            <p className="text-xs text-slate-600">
              “line” is the short tagline, “slug” the web address, “matchTerms” other spellings or
              nearby places, and “sortOrder” the position in the list. Lists (tips, bullets…) can be
              one item per line or separated by commas.
            </p>
          </div>
        }
        transformRow={(row) => {
          const name = asString(row.name);
          const line = asString(row.line);
          const description = asString(row.description);
          const bestTime = asString(row.bestTime);
          const costEstimate = asString(row.costEstimate);
          const matchTerms = asStringArray(row.matchTerms) ?? [];
          const tips = asStringArray(row.tips) ?? [];
          const bullets = asStringArray(row.bullets) ?? [];
          if (!name) throw new Error("Missing name");
          if (!line) throw new Error("Missing line");
          if (!description) throw new Error("Missing description");
          if (!bestTime) throw new Error("Missing bestTime");
          if (!costEstimate) throw new Error("Missing costEstimate");
          return {
            slug: asString(row.slug),
            name,
            line,
            description,
            heroExternalUrl: asString(row.heroExternalUrl),
            matchTerms,
            bestTime,
            tips,
            costEstimate,
            bullets,
            sortOrder: asNumber(row.sortOrder),
          };
        }}
        onImport={async (rows) => {
          return await importInBatches({
            rows,
            batchSize: 25,
            importBatch: async (batch) => {
              if (!canMutate) throw new Error("Not authenticated");
              return bulkUpsert({ sessionToken, rows: batch });
            },
            merge: (a, b) => ({
              processed: a.processed + b.processed,
              created: (a.created ?? 0) + (b.created ?? 0),
              updated: (a.updated ?? 0) + (b.updated ?? 0),
              skipped: (a.skipped ?? 0) + (b.skipped ?? 0),
              errors: [...(a.errors ?? []), ...(b.errors ?? [])],
            }),
          });
        }}
      />
    </div>
  );
}
