test("faqs: bulk update with blank sortOrder/isActive/category succeeds and preserves values", async () => {
  const t = newTest();
  const sessionToken = await signIn(t);
  const id = await t.mutation(api.faqs.upsert, {
    sessionToken,
    question: "Q1",
    answer: "A1",
    category: "Visas",
    sortOrder: 7,
    isActive: false,
  });
  const res = await t.mutation(api.faqs.bulkUpsert, {
    sessionToken,
    rows: [{ faqId: id, question: "Q1", answer: "A1 updated" }],
  });
  expect(res.errors).toEqual([]);
  expect(res.updated).toBe(1);
  const row = await t.run(async (ctx) => ctx.db.get(id));
  expect(row!.answer).toBe("A1 updated");
  expect(row!.sortOrder).toBe(7);
  expect(row!.isActive).toBe(false);
  expect(row!.category).toBe("Visas");

  // Matching by category+question also works.
  const res2 = await t.mutation(api.faqs.bulkUpsert, {
    sessionToken,
    rows: [{ question: "q1", answer: "A1 v3", category: "Visas" }],
  });
  expect(res2.updated).toBe(1);
  expect((await t.run(async (ctx) => ctx.db.get(id)))!.answer).toBe("A1 v3");

  // upsert without category keeps the category.
  await t.mutation(api.faqs.upsert, { sessionToken, faqId: id, question: "Q1", answer: "A4" });
  expect((await t.run(async (ctx) => ctx.db.get(id)))!.category).toBe("Visas");

  const page = await t.query(api.faqs.listAdminPage, {
    sessionToken,
    paginationOpts: { numItems: 10, cursor: null },
  });
  expect(page.page.map((f) => f._id)).toContain(id);
});

