// ---------------------------------------------------------------- provinces/sites

test("syncDefaultCatalog never overwrites edited provinces or sites", async () => {
  const t = newTest();
  const sessionToken = await signIn(t);

  const first = await t.mutation(api.provinces.syncDefaultCatalog, { sessionToken });
  expect(first.created).toBeGreaterThan(0);
  await t.mutation(api.sites.syncDefaultCatalog, { sessionToken });

  const sindh = await t.run(async (ctx) =>
    ctx.db.query("provinces").withIndex("by_slug", (q) => q.eq("slug", "sindh")).unique(),
  );
  await t.mutation(api.provinces.updateProvince, {
    sessionToken,
    provinceId: sindh!._id,
    tagline: "Admin-edited tagline",
    sortOrder: 42,
  });
  const site = await t.run(async (ctx) =>
    ctx.db
      .query("sites")
      .withIndex("by_province_and_slug", (q) =>
        q.eq("provinceId", sindh!._id).eq("slug", "mohenjo-daro"),
      )
      .unique(),
  );
  await t.mutation(api.sites.updateSite, {
    sessionToken,
    siteId: site!._id,
    city: "Admin City",
    isActive: false,
    featured: false,
  });

  const again = await t.mutation(api.provinces.syncDefaultCatalog, { sessionToken });
  expect(again.created).toBe(0);
  expect(again.updated).toBe(0);
  const sitesAgain = await t.mutation(api.sites.syncDefaultCatalog, { sessionToken });
  expect(sitesAgain.created).toBe(0);
  expect(sitesAgain.updated).toBe(0);

  const p = await t.run(async (ctx) => ctx.db.get(sindh!._id));
  expect(p!.tagline).toBe("Admin-edited tagline");
  expect(p!.sortOrder).toBe(42);
  const s = await t.run(async (ctx) => ctx.db.get(site!._id));
  expect(s!.city).toBe("Admin City");
  expect(s!.isActive).toBe(false);
  expect(s!.featured).toBe(false);
});

test("deleteProvince refuses while sites exist and never cascades", async () => {
  const t = newTest();
  const sessionToken = await signIn(t);
  const provinceId = await insertProvince(t, "p1", "P1");
  const siteId = await t.mutation(api.sites.createSite, {
    sessionToken,
    provinceId,
    slug: "s1",
    name: "S1",
    type: "historical",
    summary: "",
    history: "",
    featured: false,
    sortOrder: 0,
    isActive: true,
  });

  await expect(
    t.mutation(api.provinces.deleteProvince, { sessionToken, provinceId }),
  ).rejects.toThrow(/site/);
  expect(await t.run(async (ctx) => ctx.db.get(siteId))).not.toBeNull();
  expect(await t.run(async (ctx) => ctx.db.get(provinceId))).not.toBeNull();

  // Move the site elsewhere, then delete succeeds.
  const other = await insertProvince(t, "p2", "P2");
  await t.mutation(api.sites.updateSite, { sessionToken, siteId, provinceId: other });
  await t.mutation(api.provinces.deleteProvince, { sessionToken, provinceId });
  expect(await t.run(async (ctx) => ctx.db.get(provinceId))).toBeNull();
  expect((await t.run(async (ctx) => ctx.db.get(siteId)))!.provinceId).toBe(other);
});

