async function seedAbout(t: ReturnType<typeof newTest>, sessionToken: string) {
  await t.mutation(api.about.upsertAdmin, {
    sessionToken,
    eyebrow: "e",
    heading: "h",
    exploreTitle: "x",
    exploreBodyText: "x",
    missionTitle: "m",
    missionBodyText: "m",
    visionTitle: "v",
    visionBodyText: "v",
    stats: [],
  });
}

test("about: partners get stable ids and removal targets the right partner", async () => {
  const t = newTest();
  const sessionToken = await signIn(t);
  await seedAbout(t, sessionToken);
  // Legacy partners without ids.
  await t.run(async (ctx) => {
    const row = await ctx.db.query("aboutPageSettings").unique();
    await ctx.db.patch(row!._id, {
      partners: [{ name: "Legacy A" }, { name: "Legacy B" }],
    });
  });
  const cId = await t.mutation(api.about.addPartner, { sessionToken, name: "C" });
  let partners = (await t.query(api.about.getAdmin, { sessionToken }))!.partners;
  expect(partners.map((p) => p.name)).toEqual(["Legacy A", "Legacy B", "C"]);
  expect(partners.every((p) => typeof p.id === "string")).toBe(true);

  // Stale index guard: index 0 is no longer "Legacy B".
  await expect(
    t.mutation(api.about.removePartner, { sessionToken, index: 0, expectedName: "Legacy B" }),
  ).rejects.toThrow(/changed/);

  await t.mutation(api.about.removePartner, { sessionToken, partnerId: partners[1]!.id });
  partners = (await t.query(api.about.getAdmin, { sessionToken }))!.partners;
  expect(partners.map((p) => p.name)).toEqual(["Legacy A", "C"]);
  expect(partners[1]!.id).toBe(cId);

  // Legacy index-only call still works.
  await t.mutation(api.about.removePartner, { sessionToken, index: 0 });
  partners = (await t.query(api.about.getAdmin, { sessionToken }))!.partners;
  expect(partners.map((p) => p.name)).toEqual(["C"]);
});

