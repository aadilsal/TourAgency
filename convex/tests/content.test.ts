test("blog: slug uniqueness, clearable meta, bulk blanks keep meta, dupes don't crash readers", async () => {
  const t = newTest();
  const sessionToken = await signIn(t);
  const a = await t.mutation(api.blog.createPost, {
    sessionToken,
    title: "A",
    slug: "Same Slug",
    content: "x",
    metaTitle: "Meta A",
    metaDescription: "Desc A",
    published: true,
  });
  await expect(
    t.mutation(api.blog.createPost, {
      sessionToken,
      title: "B",
      slug: "same-slug",
      content: "y",
      published: false,
    }),
  ).rejects.toThrow(/already uses/);
  const b = await t.mutation(api.blog.createPost, {
    sessionToken,
    title: "B",
    slug: "other",
    content: "y",
    published: false,
  });
  await expect(
    t.mutation(api.blog.updatePost, { sessionToken, postId: b, slug: "same-slug" }),
  ).rejects.toThrow(/already uses/);
  // Saving a post with its own unchanged slug is fine.
  await t.mutation(api.blog.updatePost, { sessionToken, postId: a, slug: "same-slug", title: "A2" });

  // Bulk import with blank meta keeps existing SEO text.
  const bulk = await t.mutation(api.blog.bulkUpsert, {
    sessionToken,
    rows: [{ title: "A3", slug: "same-slug", content: "z", metaTitle: "", published: true }],
  });
  expect(bulk.errors).toEqual([]);
  let post = await t.run(async (ctx) => ctx.db.get(a));
  expect(post!.title).toBe("A3");
  expect(post!.metaTitle).toBe("Meta A");
  expect(post!.metaDescription).toBe("Desc A");

  // Editor can clear meta with null.
  await t.mutation(api.blog.updatePost, {
    sessionToken,
    postId: a,
    metaTitle: null,
    metaDescription: null,
  });
  post = await t.run(async (ctx) => ctx.db.get(a));
  expect(post!.metaTitle).toBeUndefined();
  expect(post!.metaDescription).toBeUndefined();

  // Legacy duplicate slugs don't break the public reader.
  await t.run(async (ctx) =>
    ctx.db.insert("blogPosts", {
      title: "Dupe",
      slug: "same-slug",
      content: "d",
      published: false,
      createdAt: now(),
    }),
  );
  const found = await t.query(api.blog.getPostBySlug, { slug: "same-slug" });
  expect(found!._id).toBe(a);

  const page = await t.query(api.blog.listAdminPage, {
    sessionToken,
    paginationOpts: { numItems: 2, cursor: null },
  });
  expect(page.page.length).toBe(2);
  expect(page.isDone).toBe(false);
});

