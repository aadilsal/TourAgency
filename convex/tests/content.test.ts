test("team: move works with tied sortOrders and bulk blanks keep values", async () => {
  const t = newTest();
  const sessionToken = await signIn(t);
  const ids: Id<"teamMembers">[] = [];
  await t.run(async (ctx) => {
    for (const name of ["A", "B", "C"]) {
      ids.push(
        await ctx.db.insert("teamMembers", {
          name,
          role: "r",
          sortOrder: 10,
          isActive: false,
          createdAt: now(),
          updatedAt: now(),
        }),
      );
    }
  });
  const before = await t.query(api.team.listForAdmin, { sessionToken });
  const second = before[1]!;
  await t.mutation(api.team.move, { sessionToken, id: second._id, direction: "up" });
  const after = await t.query(api.team.listForAdmin, { sessionToken });
  expect(after[0]!._id).toBe(second._id);
  expect(new Set(after.map((r) => r.sortOrder)).size).toBe(3);

  await t.mutation(api.team.bulkUpsert, {
    sessionToken,
    rows: [{ name: "A", role: "r" }],
  });
  const a = await t.run(async (ctx) => ctx.db.get(ids[0]!));
  expect(a!.isActive).toBe(false);
});
