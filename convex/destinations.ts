export const seedDefaults = mutation({
  args: { sessionToken: v.string() },
  handler: async (ctx, { sessionToken }) => {
    await requireAdminFromSession(ctx, sessionToken);
    const any = await ctx.db.query("destinations").take(1);
    if (any.length > 0) return { inserted: 0, skipped: true as const };
    const now = Date.now();
    let inserted = 0;
    for (const row of DEFAULT_DESTINATIONS) {
      await ctx.db.insert("destinations", {
        ...row,
        createdAt: now,
        updatedAt: now,
      });
      inserted++;
    }
    return { inserted, skipped: false as const };
  },
});

/**
 * Adds any missing culture + heritage default destinations by slug.
 *
 * Insert-only: an existing destination (default or admin-edited) is never
 * overwritten — this used to reset admin-written copy, heroes and sort order.
 * `updated` is kept in the return shape for compatibility and is always 0.
 */
export const syncDefaultCatalog = mutation({
  args: { sessionToken: v.string() },
  handler: async (ctx, { sessionToken }) => {
    await requireAdminFromSession(ctx, sessionToken);
    const now = Date.now();
    let created = 0;
    for (let i = 0; i < DEFAULT_DESTINATIONS.length; i++) {
      const row = DEFAULT_DESTINATIONS[i]!;
      const existing = await findDestinationBySlug(ctx, row.slug);
      if (existing) continue;
      await ctx.db.insert("destinations", {
        ...row,
        autoGenerated: false,
        createdAt: now + i,
        updatedAt: now + i,
      });
      created++;
    }
    return { created, updated: 0, total: DEFAULT_DESTINATIONS.length };
  },
});

