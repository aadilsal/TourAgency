export const bulkUpsert = mutation({
  args: {
    sessionToken: v.string(),
    rows: v.array(
      v.object({
        slug: v.optional(v.string()),
        name: v.string(),
        line: v.string(),
        description: v.string(),
        heroExternalUrl: v.optional(v.string()),
        matchTerms: v.array(v.string()),
        bestTime: v.string(),
        tips: v.array(v.string()),
        costEstimate: v.string(),
        bullets: v.array(v.string()),
        sortOrder: v.optional(v.number()),
      }),
    ),
  },
  handler: async (ctx, { sessionToken, rows }) => {
    const admin = await requireAdminFromSession(ctx, sessionToken);
    const now = Date.now();
    let created = 0;
    let updated = 0;
    let skipped = 0;
    const errors: Array<{ index: number; message: string }> = [];

    for (let i = 0; i < rows.length; i++) {
      const row = rows[i]!;
      try {
        const base = (row.slug?.trim() || slugifyLocation(row.name)).toLowerCase();
        if (!row.name.trim()) throw new Error("name is required");
        if (!row.line.trim()) throw new Error("line is required");
        if (!row.description.trim()) throw new Error("description is required");
        if (!row.bestTime.trim()) throw new Error("bestTime is required");
        if (!row.costEstimate.trim()) throw new Error("costEstimate is required");

        const normalizedSlug = base;
        const existing = await findDestinationBySlug(ctx, normalizedSlug);

        const name = row.name.trim();
        const line = row.line.trim();
        const description = row.description.trim();
        const bestTime = row.bestTime.trim();
        const costEstimate = row.costEstimate.trim();
        const heroExternalUrl = row.heroExternalUrl?.trim() || undefined;
        const matchTerms = row.matchTerms.map((t) => t.trim().toLowerCase()).filter(Boolean);
        const tips = row.tips.map((t) => t.trim()).filter(Boolean);
        const bullets = row.bullets.map((b) => b.trim()).filter(Boolean);

        if (existing) {
          // UPDATE: only write columns that were actually filled in. Blank
          // lists, a blank hero URL or a missing sortOrder keep what's there.
          const patch: Partial<Doc<"destinations">> = {
            name,
            line,
            description,
            bestTime,
            costEstimate,
            // An admin import owns the row from now on.
            autoGenerated: false,
            updatedAt: now + i,
          };
          if (heroExternalUrl) patch.heroExternalUrl = heroExternalUrl;
          if (matchTerms.length > 0) patch.matchTerms = matchTerms;
          if (tips.length > 0) patch.tips = tips;
          if (bullets.length > 0) patch.bullets = bullets;
          if (row.sortOrder !== undefined) patch.sortOrder = row.sortOrder;
          await ctx.db.patch(existing._id, patch);
          updated++;
        } else {
          const slug = await ensureUniqueSlug(ctx, normalizedSlug);
          await ctx.db.insert("destinations", {
            slug,
            name,
            line,
            description,
            heroExternalUrl,
            matchTerms,
            bestTime,
            tips,
            costEstimate,
            bullets,
            sortOrder: row.sortOrder ?? 100,
            autoGenerated: false,
            createdAt: now + i,
            updatedAt: now + i,
          });
          created++;
        }
      } catch (e) {
        errors.push({ index: i, message: e instanceof Error ? e.message : String(e) });
        skipped++;
      }
    }

    await ctx.db.insert("adminLogs", {
      action: "bulk_upsert_destinations",
      performedBy: admin._id,
      timestamp: Date.now(),
      details: `processed=${rows.length} created=${created} updated=${updated} skipped=${skipped}`,
    });

    return { processed: rows.length, created, updated, skipped, errors };
  },
});
